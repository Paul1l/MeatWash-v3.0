// Эффекты работ — только те, что модель показывает убедительно; играют после того,
// как камера доехала до ракурса:
//   wash  — мойка: пыльная машина → пена ложится сверху вниз густым слоем с подтёками
//           → стоит и сползает → смыв сверху вниз → мокрый лак сохнет (~6,6 с, fx.js);
//   gloss — риски полировки исчезают и по борту идёт свет;
//   glow  — мягкий блик проходит по детали работы и гаснет (~2 с): свет room.sweep
//           по пути GLOW[ракурс], без нового источника и без смены материалов;
//   iron  — очиститель дисков: на пыльных дисках проступают и стекают фиолетовые
//           пятна → смыв сверху вниз → чистый диск, по ободу проходит блик (~6,4 с);
//   beads — керамика: вода на капоте стягивается в бусины, они остаются; по капоту
//           проходит блик (beads.js);
//   rain  — «Антидождь»: капли на лобовом стекле собираются в бусины и скатываются
//           (drops.js), затем стекло чистое;
//   cabin — химчистка салона, весь салон: дверь водителя открывается (door.js), сиденья,
//           ковёр, торпедо и обивка в пыли, крошках и разводах → на ткань, ковёр и кожу
//           ложится белая пена → волна экстракции от торпедо к корме снимает пену вместе
//           с грязью, за ней сохнет влажный след → по сиденью проходит блик (cabin.js);
//   leather — кондиционер кожи, сиденье крупно: дверь открывается, кожа сухая, светлая и
//           матовая → средство ложится круглыми пятнами, как от аппликатора, свежее блестит →
//           кожа высыхает в глубокий сатин (остаётся, пока выбрана работа), блик по сиденью.
//   lens  — полировка фар: мутное жёлтое стекло (так фары выглядят, пока полировка не
//           выбрана) светлеет до прозрачного, проступает отражатель, проходит блик (~3,2 с);
